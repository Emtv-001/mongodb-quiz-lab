import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';
import ts from 'typescript';
function load(path, imports) {
  const module = { exports: {} };
  const { outputText } = ts.transpileModule(readFileSync(new URL(path, import.meta.url), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, esModuleInterop: false } });
  new Function('require', 'module', 'exports', outputText)(name => imports[name], module, module.exports);
  return module.exports.default;
}
const response = () => ({ setHeader() {}, status(code) { this.code = code; return this; }, json(data) { this.data = data; return this; } });

test('bank grows beyond 189, deduplicates by id, and preserves concurrent additions', async () => {
  const rows = new Map(Array.from({ length: 189 }, (_, i) => ['q' + i, { id: 'q' + i }]));
  const handler = load('../api/questions.ts', {
    './_utils/db.js': { default: async () => {} },
    './_models/CustomQuestion.js': { default: {
      find: async () => [...rows.values()],
      bulkWrite: async operations => { for (const { updateOne: op } of operations) rows.set(op.filter.id, op.update.$set); }
    } }
  });
  const send = async questions => {
    const res = response();
    await handler({ method: 'POST', query: {}, body: questions.map(q => ({ title: 'Question', topic: 'CRUD Operations', difficulty: 'Medium', level: 3, points: 10, type: 'write-command', ...q })) }, res);
    assert.equal(res.code, 200);
    return res;
  };
  await send(Array.from({ length: 20 }, (_, i) => ({ id: 'ai' + i })));
  // A stale admin snapshot must not erase the questions just generated by learners.
  await send([{ id: 'q0', title: 'Edited' }]);
  const res = await send([{ id: 'ai0' }]);
  assert.equal(res.data.questions.length, 209);
  assert.equal(rows.get('q0').title, 'Edited');
});

test('invite is consumed once, assigns server permissions, and rolls back if account creation fails', async () => {
  const invite = { _id: 'invite', invitationCode: 'INV-123', status: 'pending', expiresAt: Date.now() + 100000, role: 'editor', permissions: { canManageQuestions: true }, recoveryPhrase: 'unique phrase', createdBy: 'chief' };
  let failCreation = true;
  let created;
  const handler = load('../api/admin/_invites.ts', {
    '../_utils/db.js': { default: async () => {} },
    mongoose: { default: { startSession: async () => ({
      async withTransaction(fn) {
        const before = structuredClone(invite);
        try { await fn(); } catch (error) { Object.assign(invite, before); throw error; }
      }, async endSession() {}
    }) } },
    '../_models/AdminInvite.js': { default: {
      async findOneAndUpdate(filter, update) {
        if (invite.status !== filter.status || invite.expiresAt <= filter.expiresAt.$gt) return null;
        Object.assign(invite, update.$set); return invite;
      }, async updateOne(_filter, update) { Object.assign(invite, update.$set); }
    } },
    '../_models/Admin.js': { default: { async create([user]) {
      if (failCreation) throw new Error('Account creation failed');
      created = user; return [{ ...user, _id: 'new-admin' }];
    } } }
  });
  const req = { method: 'POST', body: { action: 'accept', invitationCode: 'INV-123', username: 'newadmin', email: 'a@example.test', passwordHash: 'hash', role: 'super-admin', permissions: { all: true } } };
  const failed = response(); await handler(req, failed);
  assert.equal(failed.code, 500);
  assert.equal(invite.status, 'pending');
  failCreation = false;
  const accepted = response(); await handler(req, accepted);
  assert.equal(accepted.code, 200);
  assert.equal(invite.status, 'accepted');
  assert.equal(invite.acceptedBy, 'new-admin');
  assert.equal(created.role, 'editor');
  assert.deepEqual(created.permissions, { canManageQuestions: true });
  const reused = response(); await handler(req, reused);
  assert.equal(reused.data.success, false);
});
